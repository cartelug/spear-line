import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Concatenates src/styles/*.css (in file-name order) into public/site.css, the only stylesheet pages load.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = resolve(root, "src/styles");
const sources = (await readdir(sourceDir)).filter(name => name.endsWith(".css")).sort();
const parts = [];
for (const name of sources) {
  const css = (await readFile(resolve(sourceDir, name), "utf8")).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n\s*/g, "\n").replace(/\n{2,}/g, "\n").trim();
  parts.push(css);
}
const bundle = "/* Generated by scripts/bundle-css.mjs from src/styles. Edit those files, then run npm run build. */\n" + parts.join("\n") + "\n";
const target = resolve(root, "public/site.css");
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== bundle) throw new Error("public/site.css is out of date. Run npm run build.");
  console.log("site.css matches src/styles (" + sources.length + " files).");
} else {
  await writeFile(target, bundle);
  console.log("Bundled " + sources.length + " stylesheets into public/site.css (" + bundle.length + " bytes).");
}
