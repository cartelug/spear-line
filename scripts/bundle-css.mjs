import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// The four hand-edited stylesheets are served as one file, so first paint waits on a single request.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "public");
const sources = ["styles.css", "experience.css", "motion.css", "pro.css"];
const parts = [];
for (const name of sources) {
  const css = (await readFile(resolve(root, name), "utf8")).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n\s*/g, "\n").trim();
  parts.push(css);
}
const bundle = "/* Generated by scripts/bundle-css.mjs from " + sources.join(", ") + ". Edit those files, then run npm run render:pages. */\n" + parts.join("\n") + "\n";
const target = resolve(root, "site.css");
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== bundle) throw new Error("public/site.css is out of date. Run npm run render:pages.");
  console.log("site.css matches its sources.");
} else {
  await writeFile(target, bundle);
  console.log("Bundled " + sources.length + " stylesheets into site.css (" + bundle.length + " bytes).");
}
